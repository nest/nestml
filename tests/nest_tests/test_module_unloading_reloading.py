import os
import re
import shutil
import tempfile

import pytest

import nest

from pynestml.codegeneration.nest_tools import NESTTools
from pynestml.frontend.pynestml_frontend import generate_nest_target


def _nest_resetkernel_unloads_modules() -> bool:
    r"""ResetKernel() only unloads dynamically loaded modules as of NEST Simulator v3.7."""
    nest_version = NESTTools.detect_nest_version()
    m = re.match(r"v(\d+)\.(\d+)", nest_version)
    if m is None:
        # development branch (e.g. "master"): assume a recent version
        return True

    return (int(m.group(1)), int(m.group(2))) >= (3, 7)


@pytest.mark.skipif(not _nest_resetkernel_unloads_modules(),
                    reason="ResetKernel() does not unload modules for NEST Simulator < v3.7")
class TestModuleUnloadingReloading:
    r"""
    Test that a NESTML-generated module can be unloaded (by ``nest.ResetKernel()``) and that a different module, built under the same filename, is correctly loaded afterwards.

    If the module could not be unloaded (for instance, due to ``STB_GNU_UNIQUE`` symbols generated by GCC, which mark the shared object as non-unloadable), then ``dlopen()`` returns the handle of the previously loaded module, and the models of the first module are registered again instead of the models of the second module. This happened in particular when ``nest.CopyModel()`` had been called on one of the models in the module.
    """

    module_name = "nestml_reload_test_module"

    synapse_model_template = """
model {model_name}:
    parameters:
        w real = {default_weight}

    input:
        pre_spikes <- spike

    output:
        spike

    onReceive(pre_spikes):
        emit_spike(w)
"""

    @pytest.fixture(autouse=True)
    def paths(self):
        self.tmp_dir = tempfile.mkdtemp(prefix="nestml_module_reload_test")
        self.input_dir = os.path.join(self.tmp_dir, "models")
        self.target_path = os.path.join(self.tmp_dir, "target")
        self.install_path = os.path.join(self.tmp_dir, "install")
        os.makedirs(self.input_dir)
        os.makedirs(self.install_path)

        yield

        nest.ResetKernel()
        shutil.rmtree(self.tmp_dir, ignore_errors=True)

    def _generate_and_build(self, model_name: str, default_weight: float) -> str:
        r"""Generate and build a module containing a single synapse model. The module is always built into the same target and install directory, so that the resulting ``.so`` file has the same absolute path every time."""
        for fn in os.listdir(self.input_dir):
            os.remove(os.path.join(self.input_dir, fn))

        input_fn = os.path.join(self.input_dir, model_name + ".nestml")
        with open(input_fn, "w") as f:
            f.write(self.synapse_model_template.format(model_name=model_name, default_weight=default_weight))

        generate_nest_target(input_path=input_fn,
                             target_path=self.target_path,
                             install_path=self.install_path,
                             logging_level="WARNING",
                             module_name=self.module_name,
                             codegen_opts={"weight_variable": {model_name: "w"}})

        module_fn = os.path.join(self.install_path, self.module_name + ".so")
        assert os.path.isfile(module_fn)

        return module_fn

    def _install_and_check(self, module_fn: str, expected_model_name: str, expected_default_weight: float, unexpected_model_names=()):
        nest.ResetKernel()
        NESTTools.set_nest_verbosity("ALL")
        nest.Install(module_fn)

        assert expected_model_name in nest.synapse_models
        for unexpected_model_name in unexpected_model_names:
            assert unexpected_model_name not in nest.synapse_models

        # check that the contents of the module (and not just the model names) are those of the most recently built module
        assert nest.GetDefaults(expected_model_name)["w"] == pytest.approx(expected_default_weight)

        # use the model to make sure that it is functional
        pre = nest.Create("spike_generator", params={"spike_times": [10.]})
        post = nest.Create("parrot_neuron")
        nest.Connect(pre, post, syn_spec={"synapse_model": expected_model_name})
        assert nest.GetConnections(synapse_model=expected_model_name).w == pytest.approx(expected_default_weight)
        nest.Simulate(20.)

        # copying a model triggered the original issue: the module could not be unloaded afterwards
        nest.CopyModel(expected_model_name, "foo_synapse")
        assert "foo_synapse" in nest.synapse_models

    def test_module_unloading_reloading(self):
        # first module: "a_synapse"
        module_fn = self._generate_and_build("a_synapse", 1.23)
        self._install_and_check(module_fn, "a_synapse", 1.23)

        # second module (same filename, different contents): "b_synapse"
        module_fn_b = self._generate_and_build("b_synapse", 4.56)
        assert module_fn_b == module_fn
        self._install_and_check(module_fn, "b_synapse", 4.56, unexpected_model_names=["a_synapse", "foo_synapse"])

        # third module (same filename, same model name as the first module, but different contents)
        module_fn_a2 = self._generate_and_build("a_synapse", 7.89)
        assert module_fn_a2 == module_fn
        self._install_and_check(module_fn, "a_synapse", 7.89, unexpected_model_names=["b_synapse", "foo_synapse"])
